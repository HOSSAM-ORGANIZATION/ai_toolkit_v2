import sys
import os
import re
import json
from pathlib import Path

def load_simple_yaml(file_path):
    """Simple parser extracting top-level keys and string lists."""
    data = {}
    if not os.path.exists(file_path):
        return data
    with open(file_path, "r", encoding="utf-8") as f:
        lines = f.readlines()
    
    current_key = None
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        top_match = re.match(r"^([a-zA-Z0-9_\-]+)\s*:\s*(.*)", line)
        if top_match and not raw.startswith(" ") and not raw.startswith("\t"):
            key = top_match.group(1)
            val = top_match.group(2).strip().strip("'\"")
            current_key = key
            if val:
                data[key] = val
            else:
                data[key] = []
            continue
        list_match = re.match(r"^\s*-\s*[\"']?([a-zA-Z0-9_\-]+)[\"']?", line)
        if list_match and current_key:
            item = list_match.group(1).strip()
            if isinstance(data.get(current_key), list):
                data[current_key].append(item)
    return data

def setup_dart_entrypoints(target_dir, flavors, project_name):
    """Creates lib/main_<flavor>.dart and lib/config/environment_config.dart using modern appFlavor."""
    lib_dir = Path(target_dir) / "lib"
    lib_dir.mkdir(parents=True, exist_ok=True)
    config_dir = lib_dir / "config"
    config_dir.mkdir(parents=True, exist_ok=True)

    # 1. Environment Config
    env_file = config_dir / "environment_config.dart"
    if not env_file.exists():
        flavors_enum = "\n".join([f"  {fl}," for fl in flavors])
        env_content = f"""// Generated by Universal AI Toolkit v2 — Flavor Environment Configuration
import 'package:flutter/services.dart';

enum AppFlavor {{
{flavors_enum}
}}

class EnvironmentConfig {{
  final AppFlavor flavor;
  final String appName;
  final String baseUrl;

  const EnvironmentConfig({{
    required this.flavor,
    required this.appName,
    required this.baseUrl,
  }});

  static EnvironmentConfig? _current;
  static EnvironmentConfig get current {{
    if (_current == null) {{
      // Fallback to official Flutter appFlavor if available
      final detected = appFlavor ?? '{flavors[0]}';
      _current = fromFlavorString(detected);
    }}
    return _current!;
  }}

  static void initialize(EnvironmentConfig config) {{
    _current = config;
  }}

  static EnvironmentConfig fromFlavorString(String name) {{
    switch (name.toLowerCase()) {{
"""
        for fl in flavors:
            env_content += f"""      case '{fl}':
        return const EnvironmentConfig(
          flavor: AppFlavor.{fl},
          appName: '{project_name.capitalize()} {fl.capitalize()}',
          baseUrl: 'https://api.{fl}.example.com',
        );
"""
        env_content += f"""      default:
        return const EnvironmentConfig(
          flavor: AppFlavor.{flavors[0]},
          appName: '{project_name.capitalize()} {flavors[0].capitalize()}',
          baseUrl: 'https://api.{flavors[0]}.example.com',
        );
    }}
  }}
}}
"""
        with open(env_file, "w", encoding="utf-8") as f:
            f.write(env_content)
        print(f"   ✅ Created: lib/config/environment_config.dart")

    # 2. Main entrypoints per flavor
    for fl in flavors:
        entry_file = lib_dir / f"main_{fl}.dart"
        if not entry_file.exists():
            entry_content = f"""// Generated by Universal AI Toolkit v2 — Modern Flutter Entrypoint
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'config/environment_config.dart';

void main() async {{
  WidgetsFlutterBinding.ensureInitialized();
  
  // Modern Flutter 3.10+ appFlavor resolution
  final resolvedFlavor = appFlavor ?? '{fl}';
  EnvironmentConfig.initialize(EnvironmentConfig.fromFlavorString(resolvedFlavor));

  runApp(const MyApp());
}}

class MyApp extends StatelessWidget {{
  const MyApp({{super.key}});

  @override
  Widget build(BuildContext context) {{
    final env = EnvironmentConfig.current;
    return MaterialApp(
      title: env.appName,
      debugShowCheckedModeBanner: false,
      theme: ThemeData(
        colorScheme: ColorScheme.fromSeed(seedColor: Colors.deepPurple),
        useMaterial3: true,
      ),
      home: Scaffold(
        appBar: AppBar(title: Text(env.appName)),
        body: Center(
          child: Column(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              Text('Active Flavor: ${{env.flavor.name}}', style: Theme.of(context).textTheme.headlineSmall),
              const SizedBox(height: 12),
              Text('Base URL: ${{env.baseUrl}}'),
            ],
          ),
        ),
      ),
    );
  }}
}}
"""
            with open(entry_file, "w", encoding="utf-8") as f:
                f.write(entry_content)
            print(f"   ✅ Created: lib/main_{fl}.dart")

def setup_pubspec_default_flavor(target_dir, default_flavor):
    """Sets flutter.default-flavor in pubspec.yaml according to modern Flutter docs."""
    pubspec_path = Path(target_dir) / "pubspec.yaml"
    if not pubspec_path.exists():
        return
    with open(pubspec_path, "r", encoding="utf-8") as f:
        content = f.read()
    
    if "default-flavor:" not in content:
        # Match top-level flutter: section (not dependencies: flutter:)
        if re.search(r"^flutter:\s*$", content, flags=re.MULTILINE):
            content = re.sub(
                r"(^flutter:\s*\n)",
                f"\\1  default-flavor: {default_flavor}\n",
                content,
                count=1,
                flags=re.MULTILINE
            )
            with open(pubspec_path, "w", encoding="utf-8") as f:
                f.write(content)
            print(f"   ✅ Added 'default-flavor: {default_flavor}' to pubspec.yaml")

def setup_android_flavors(target_dir, flavors, project_name):
    """Configures productFlavors in android/app/build.gradle(.kts) and res values."""
    android_app_dir = Path(target_dir) / "android" / "app"
    if not android_app_dir.exists():
        return

    # 1. Android strings.xml resources per flavor
    for fl in flavors:
        res_dir = android_app_dir / "src" / fl / "res" / "values"
        res_dir.mkdir(parents=True, exist_ok=True)
        strings_file = res_dir / "strings.xml"
        if not strings_file.exists():
            xml_content = f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
    <string name="app_name">{project_name.capitalize()} {fl.capitalize()}</string>
</resources>
"""
            with open(strings_file, "w", encoding="utf-8") as f:
                f.write(xml_content)
            print(f"   ✅ Created: android/app/src/{fl}/res/values/strings.xml")

    # 2. Update build.gradle.kts (Kotlin DSL) or build.gradle (Groovy)
    kts_path = android_app_dir / "build.gradle.kts"
    groovy_path = android_app_dir / "build.gradle"

    if kts_path.exists():
        with open(kts_path, "r", encoding="utf-8") as f:
            content = f.read()
        if "flavorDimensions" not in content and "productFlavors" not in content:
            flavors_code = '\n    flavorDimensions += "default"\n    productFlavors {\n'
            for fl in flavors:
                flavors_code += f'''        create("{fl}") {{
            dimension = "default"
            applicationIdSuffix = ".{fl}"
            resValue("string", "app_name", "{project_name.capitalize()} {fl.capitalize()}")
        }}\n'''
            flavors_code += '    }\n'
            # Insert inside android block
            if "android {" in content:
                content = content.replace("android {", "android {" + flavors_code, 1)
                with open(kts_path, "w", encoding="utf-8") as f:
                    f.write(content)
                print("   ✅ Injected productFlavors into android/app/build.gradle.kts")
    elif groovy_path.exists():
        with open(groovy_path, "r", encoding="utf-8") as f:
            content = f.read()
        if "flavorDimensions" not in content and "productFlavors" not in content:
            flavors_code = '\n    flavorDimensions "default"\n    productFlavors {\n'
            for fl in flavors:
                flavors_code += f'''        {fl} {{
            dimension "default"
            applicationIdSuffix ".{fl}"
            resValue "string", "app_name", "{project_name.capitalize()} {fl.capitalize()}"
        }}\n'''
            flavors_code += '    }\n'
            if "android {" in content:
                content = content.replace("android {", "android {" + flavors_code, 1)
                with open(groovy_path, "w", encoding="utf-8") as f:
                    f.write(content)
                print("   ✅ Injected productFlavors into android/app/build.gradle")

def setup_ios_flavors(target_dir, flavors, project_name):
    """Creates iOS xcconfig files, dynamic Info.plist app name, and Xcode shared schemes."""
    ios_dir = Path(target_dir) / "ios"
    if not ios_dir.exists():
        return

    flutter_dir = ios_dir / "Flutter"
    flutter_dir.mkdir(parents=True, exist_ok=True)

    # 1. xcconfig files per flavor
    for fl in flavors:
        debug_xc = flutter_dir / f"Debug-{fl}.xcconfig"
        if not debug_xc.exists():
            with open(debug_xc, "w", encoding="utf-8") as f:
                f.write(f'#include "Debug.xcconfig"\n#include "Generated.xcconfig"\nPRODUCT_BUNDLE_IDENTIFIER = com.example.{project_name}.{fl}\nAPP_DISPLAY_NAME = {project_name.capitalize()} {fl.capitalize()}\n')
            print(f"   ✅ Created: ios/Flutter/Debug-{fl}.xcconfig")

        release_xc = flutter_dir / f"Release-{fl}.xcconfig"
        if not release_xc.exists():
            with open(release_xc, "w", encoding="utf-8") as f:
                f.write(f'#include "Release.xcconfig"\n#include "Generated.xcconfig"\nPRODUCT_BUNDLE_IDENTIFIER = com.example.{project_name}.{fl}\nAPP_DISPLAY_NAME = {project_name.capitalize()} {fl.capitalize()}\n')
            print(f"   ✅ Created: ios/Flutter/Release-{fl}.xcconfig")

    # 2. Update Info.plist to use $(APP_DISPLAY_NAME)
    info_plist = ios_dir / "Runner" / "Info.plist"
    if info_plist.exists():
        with open(info_plist, "r", encoding="utf-8") as f:
            content = f.read()
        if "<key>CFBundleDisplayName</key>" in content:
            content = re.sub(
                r"<key>CFBundleDisplayName</key>\s*<string>[^<]*</string>",
                "<key>CFBundleDisplayName</key>\n\t<string>$(APP_DISPLAY_NAME)</string>",
                content
            )
            with open(info_plist, "w", encoding="utf-8") as f:
                f.write(content)
            print("   ✅ Updated ios/Runner/Info.plist CFBundleDisplayName -> $(APP_DISPLAY_NAME)")

    # 3. Create Xcode Shared Schemes
    schemes_dir = ios_dir / "Runner.xcodeproj" / "xcshareddata" / "xcschemes"
    schemes_dir.mkdir(parents=True, exist_ok=True)
    for fl in flavors:
        scheme_file = schemes_dir / f"{fl}.xcscheme"
        if not scheme_file.exists():
            scheme_content = f"""<?xml version="1.0" encoding="UTF-8"?>
<Scheme
   LastUpgradeVersion = "1510"
   version = "1.7">
   <BuildAction
      parallelizeBuildables = "YES"
      buildImplicitDependencies = "YES">
      <BuildActionEntries>
         <BuildActionEntry
            buildForTesting = "YES"
            buildForRunning = "YES"
            buildForProfiling = "YES"
            buildForArchiving = "YES"
            buildForAnalyzing = "YES">
            <BuildableReference
               BuildableIdentifier = "primary"
               BlueprintIdentifier = "97C146ED1CF9000F007C117D"
               BuildableName = "Runner.app"
               BlueprintName = "Runner"
               ReferencedContainer = "container:Runner.xcodeproj">
            </BuildableReference>
         </BuildActionEntry>
      </BuildActionEntries>
   </BuildAction>
   <LaunchAction
      buildConfiguration = "Debug-{fl}"
      selectedDebuggerIdentifier = "Xcode.DebuggerFoundation.Debugger.LLDB"
      selectedLauncherIdentifier = "Xcode.DebuggerFoundation.Launcher.LLDB"
      launchStyle = "0"
      useLaunchSchemeArgsEnv = "YES">
   </LaunchAction>
   <ProfileAction
      buildConfiguration = "Release-{fl}"
      shouldUseLaunchSchemeArgsEnv = "YES">
   </ProfileAction>
   <AnalyzeAction
      buildConfiguration = "Debug-{fl}">
   </AnalyzeAction>
   <ArchiveAction
      buildConfiguration = "Release-{fl}"
      revealArchiveInOrganizer = "YES">
   </ArchiveAction>
</Scheme>
"""
            with open(scheme_file, "w", encoding="utf-8") as f:
                f.write(scheme_content)
            print(f"   ✅ Created Xcode scheme: ios/Runner.xcodeproj/xcshareddata/xcschemes/{fl}.xcscheme")

def setup_vscode_launch(target_dir, flavors):
    """Generates .vscode/launch.json for 1-click debugging in Cursor / VS Code."""
    vscode_dir = Path(target_dir) / ".vscode"
    vscode_dir.mkdir(parents=True, exist_ok=True)
    launch_file = vscode_dir / "launch.json"

    configs = []
    for fl in flavors:
        configs.append({
            "name": f"{fl.capitalize()} (Debug)",
            "request": "launch",
            "type": "dart",
            "program": f"lib/main_{fl}.dart",
            "args": ["--flavor", fl]
        })
        configs.append({
            "name": f"{fl.capitalize()} (Profile)",
            "request": "launch",
            "type": "dart",
            "flutterMode": "profile",
            "program": f"lib/main_{fl}.dart",
            "args": ["--flavor", fl]
        })

    launch_data = {
        "version": "0.2.0",
        "configurations": configs
    }
    with open(launch_file, "w", encoding="utf-8") as f:
        json.dump(launch_data, f, indent=2)
    print("   ✅ Generated .vscode/launch.json configurations for all flavors")

def setup_flavors(target_dir="."):
    target_path = Path(target_dir).resolve()
    profile_path = target_path / "project_profile.yaml"

    if not profile_path.exists():
        print(f"❌ Error: {profile_path} not found. Run 'toolkit init' first.")
        return False

    profile = load_simple_yaml(profile_path)
    proj_type = profile.get("project_type", "single_app")
    flavors = profile.get("flavors", [])
    proj_name = profile.get("project_name", target_path.name)

    print("\n" + "🎨"*35)
    print("  UNIVERSAL AI TOOLKIT v2 — MODERN FLAVORS SETUP")
    print("🎨"*35)
    print(f"📂 Target Directory: {target_path}")
    print(f"🏢 Project Type: {proj_type}")

    if proj_type != "multi_flavor" or not flavors:
        print("ℹ️ Project is configured as single_app (no flavors defined). Nothing to set up.")
        print("="*70 + "\n")
        return True

    print(f"🏷️ Flavors ({len(flavors)}): {', '.join(flavors)}")
    print("\n⚙️ Setting up modern Flutter flavors across all platforms...")

    # 1. Dart & pubspec
    setup_dart_entrypoints(target_path, flavors, proj_name)
    setup_pubspec_default_flavor(target_path, flavors[0])

    # 2. Android
    setup_android_flavors(target_path, flavors, proj_name)

    # 3. iOS
    setup_ios_flavors(target_path, flavors, proj_name)

    # 4. VS Code / Cursor
    setup_vscode_launch(target_path, flavors)

    print("\n🎉 Modern Flutter Flavors setup completed successfully!")
    print("💡 Run any flavor using:")
    for fl in flavors:
        print(f"   • flutter run --flavor {fl} -t lib/main_{fl}.dart")
    print("="*70 + "\n")
    return True

if __name__ == "__main__":
    target = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("--") else "."
    setup_flavors(target)
